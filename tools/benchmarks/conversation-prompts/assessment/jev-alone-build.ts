import {compareCurrent} from './current-comparison.ts';
import {evaluateDecision} from './decision-gates.ts';
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {build} from 'esbuild';
import {hash} from './plan.ts';
import {loadJev} from './jev-alone-analysis.ts';
import {renderDocument} from '../explorer/document.ts';
const [directory,mode]=process.argv.slice(2);
if(!directory||mode&&mode!=='--profiles-only')throw Error('Usage: jev-alone-build.ts OUT [--profiles-only]');
const data=loadJev(directory);
const unique=[...new Map(data.rows.filter(r=>r.status==='complete').map(r=>[r.profileHash,r.vector])).entries()].sort(([a],[b])=>a.localeCompare(b));
const signature=hash(JSON.stringify(unique));
writeFileSync(directory+'/profiles.json',JSON.stringify({signature,hashes:unique.map(([h])=>h),vectors:unique.map(([,v])=>v)}));
if(mode==='--profiles-only'){console.log(JSON.stringify({profiles:unique.length,signature}));process.exit(0);}
const projections=existsSync(directory+'/projections.json')?JSON.parse(readFileSync(directory+'/projections.json','utf8')):null;
if(projections&&projections.corpusSignature!==signature)throw Error('Recompute projections for changed corpus');
const bundle=await build({entryPoints:['tools/benchmarks/conversation-prompts/assessment/jev-alone-view.ts'],bundle:true,write:false,format:'iife',minify:true,target:'es2022'});
const style=readFileSync('tools/benchmarks/conversation-prompts/explorer/view.html','utf8').match(/<style>[\s\S]*?<\/style>/)?.[0];if(!style)throw Error('Missing shared foundations');
const template=readFileSync('tools/benchmarks/conversation-prompts/assessment/jev-alone-view.html','utf8').replace('<!--STYLE-->',()=>style);
const decision=data.acceptance?evaluateDecision(data):null;
const current=compareCurrent(directory,data);
const recommendation=existsSync(directory+'/recommendation.json')?JSON.parse(readFileSync(directory+'/recommendation.json','utf8')):null;
if(recommendation&&(!current?.complete||recommendation.currentPlanHash!==current.currentPlanHash||recommendation.jevPlanHash!==current.jevPlanHash))throw Error('Recommendation does not match completed comparison');
const dataset={...data,projections,decision,current,recommendation};
if(current)writeFileSync(directory+'/current-comparison.json',JSON.stringify(current,null,2));
if(decision)writeFileSync(directory+'/decision-report.json',JSON.stringify(decision,null,2));
const html=renderDocument(template,dataset,bundle.outputFiles[0].text);
if(Buffer.byteLength(html)>30000000)throw Error('Dashboard exceeds 30 MB');
writeFileSync(directory+'/index.html',html);writeFileSync(directory+'/analysis.json',JSON.stringify(dataset));
writeFileSync(directory+'/sdt-report.json',JSON.stringify({planHash:data.planHash,referenceStatus:'provisional',reports:data.reports},null,2));
console.log(JSON.stringify({rows:data.rows.length,planned:data.planned,profiles:unique.length,projections:projections?.projections.length??0,bytes:Buffer.byteLength(html)}));
