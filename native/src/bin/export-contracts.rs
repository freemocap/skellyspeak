fn main() -> Result<(), Box<dyn std::error::Error>> {
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../ui/src/generated/contracts.ts");
    let expected = skellyspeak_core::model::bindings();
    if std::env::args().any(|arg| arg == "--check") {
        if std::fs::read_to_string(&path)? != expected {
            return Err("Generated TypeScript contracts are stale; run npm run contracts".into());
        }
    } else {
        std::fs::write(path, expected)?;
    }
    let catalog_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../ui/src/generated/skill-catalogs/catalog.json");
    let catalog = format!(
        "{}\n",
        serde_json::to_string_pretty(&skellyspeak_core::learning::coaching::catalog())?
    );
    if std::env::args().any(|arg| arg == "--check") {
        if std::fs::read_to_string(catalog_path)? != catalog {
            return Err("Generated construct catalog is stale; run npm run contracts".into());
        }
    } else {
        std::fs::write(catalog_path, catalog)?;
    }
    let speech_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../server/app/inference/speech_catalog.py");
    let speech =
        serde_json::to_string(skellyspeak_core::configuration::speech::Catalog::bundled())?;
    let source = std::fs::read_to_string(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../content/shared/speech-routing.yaml"),
    )?;
    let hash = source_digest(&source);
    let speech = format!(
        "# Generated by npm run contracts; edit content/shared/speech-routing.yaml.\nimport json\nSOURCE_SHA256 = {hash:?}\nCATALOG = json.loads({})\n",
        serde_json::to_string(&speech)?
    );
    if std::env::args().any(|arg| arg == "--check") {
        if std::fs::read_to_string(&speech_path)? != speech {
            return Err("Generated speech catalog is stale; run npm run contracts".into());
        }
    } else {
        std::fs::write(speech_path, speech)?;
    }
    Ok(())
}

fn source_digest(source: &str) -> String {
    use sha2::Digest;
    // Match repository LF text even when a local editor has written CRLF.
    format!(
        "{:x}",
        sha2::Sha256::digest(source.replace("\r\n", "\n").as_bytes())
    )
}

#[cfg(test)]
mod tests {
    use super::source_digest;

    #[test]
    fn source_digest_ignores_checkout_line_endings_but_detects_content_changes() {
        assert_eq!(
            source_digest("first\nsecond\n"),
            source_digest("first\r\nsecond\r\n")
        );
        assert_ne!(
            source_digest("first\nsecond\n"),
            source_digest("first\nchanged\n")
        );
    }
}
